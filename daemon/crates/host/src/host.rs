//! WebSocket server, connection registry and event routing.
//!
//! Threads: one blocking accept loop, one blocking reader per socket, and one waiter thread per
//! launched plugin that blocks on `Child::wait` and restarts it with backoff on a crash. Writes go
//! through a second tungstenite handle on a clone of the same TCP stream, behind a mutex, so any
//! thread can send without waiting for the reader. Nothing polls.

use crate::launch::{self, Device};
use crate::manifest::Plugin;
use serde_json::{json, Value};
use std::collections::{HashMap, HashSet};
use std::io::{self, Read, Write};
use std::net::{Shutdown, TcpListener, TcpStream};
use std::path::PathBuf;
use std::process::{Child, Command, Stdio};
use std::sync::atomic::{AtomicBool, AtomicU64, Ordering};
use std::sync::{Arc, Mutex, MutexGuard};
use std::time::{Duration, Instant};
use tungstenite::handshake::server::{ErrorResponse, Request, Response};
use tungstenite::protocol::{Role as WsRole, WebSocketConfig};
use tungstenite::{Message, WebSocket};

/// Host settings.
#[derive(Debug, Clone)]
pub struct Config {
    /// Loopback port. 18618 makes the host a drop-in for Stream Dock (never run both); 0 picks a
    /// free port, see [`Host::port`].
    pub port: u16,
    /// Node binary for `.js/.mjs/.cjs` plugins.
    pub node: PathBuf,
    /// Devices reported in `-info` and `deviceDidConnect`.
    pub devices: Vec<Device>,
    /// `info.application.language`.
    pub language: String,
    /// Browser origins allowed to open a socket, matched exactly, e.g. the web editor's
    /// `http://127.0.0.1:<port>`. Sockets without an Origin header (native plugin processes) are
    /// always allowed. `"null"` (file:// pages, sandboxed frames) is rejected unless listed here;
    /// the daemon also admits it while an inspector session exists (a sandboxed PI iframe), and
    /// even then the socket needs a single-use inspector token from [`Host::open_inspector`].
    pub origins: Vec<String>,
}

impl Default for Config {
    fn default() -> Self {
        Config {
            port: 18618,
            node: "node".into(),
            devices: Vec::new(),
            language: "en".into(),
            origins: Vec::new(),
        }
    }
}

/// One action placed on a key (an Elgato "context"). The context id itself is generated by
/// [`Host::appear`] from the OS CSPRNG, so callers cannot choose or predict it.
#[derive(Debug, Clone, PartialEq)]
pub struct Instance {
    context: String,
    /// Plugin id ([`Plugin::id`]).
    pub plugin: String,
    /// Action UUID from the manifest.
    pub action: String,
    pub device: String,
    pub column: u32,
    pub row: u32,
    /// `Keypad`, or `Information` for the AKP153E side cells (column 5).
    pub controller: String,
    pub settings: Value,
    pub state: u32,
}

impl Instance {
    /// A `Keypad` instance in state 0 with empty settings.
    pub fn new(plugin: &str, action: &str, device: &str, column: u32, row: u32) -> Self {
        Instance {
            context: String::new(),
            plugin: plugin.into(),
            action: action.into(),
            device: device.into(),
            column,
            row,
            controller: "Keypad".into(),
            settings: json!({}),
            state: 0,
        }
    }

    /// The context assigned by [`Host::appear`]; empty before that.
    pub fn context(&self) -> &str {
        &self.context
    }

    fn key(&self) -> Key {
        Key {
            context: self.context.clone(),
            device: self.device.clone(),
            column: self.column,
            row: self.row,
        }
    }
}

/// Where an output goes.
#[derive(Debug, Clone, PartialEq)]
pub struct Key {
    pub context: String,
    pub device: String,
    pub column: u32,
    pub row: u32,
}

/// What plugins ask the daemon to do. Images are passed through as sent (usually a
/// `data:image/...;base64,` or SVG data URI); decoding, coalescing and rate limiting belong to the
/// renderer.
#[derive(Debug, Clone, PartialEq)]
pub enum Output {
    Image {
        key: Key,
        image: String,
        state: Option<u32>,
    },
    Title {
        key: Key,
        title: String,
        state: Option<u32>,
    },
    State {
        key: Key,
        state: u32,
    },
    ShowOk(Key),
    ShowAlert(Key),
    /// Action settings changed: persist them in the profile.
    Settings {
        context: String,
        settings: Value,
    },
    /// Plugin global settings changed: persist them, then seed with [`Host::load_global_settings`].
    GlobalSettings {
        plugin: String,
        settings: Value,
    },
    OpenUrl(String),
}

/// Receives [`Output`]s. Called on socket threads with no host lock held, so it may call back into
/// the [`Host`]. Any `Fn(Output) + Send + Sync` closure is an `Events`.
pub trait Events: Send + Sync + 'static {
    fn output(&self, out: Output);
}

impl<F: Fn(Output) + Send + Sync + 'static> Events for F {
    fn output(&self, out: Output) {
        self(out)
    }
}

/// The plugin host. Cheap to clone; all clones share one server.
#[derive(Clone)]
pub struct Host {
    inner: Arc<Inner>,
}

struct Inner {
    cfg: Config,
    port: u16,
    events: Box<dyn Events>,
    state: Mutex<State>,
    /// Browser origins, seeded from [`Config::origins`] and extendable at runtime.
    origins: Mutex<Vec<String>>,
    next_id: AtomicU64,
}

#[derive(Default)]
struct State {
    plugins: HashMap<String, Slot>,
    /// Per-launch plugin UUID -> plugin id.
    uuids: HashMap<String, String>,
    instances: HashMap<String, Instance>,
    /// Context -> property inspector socket.
    pis: HashMap<String, Arc<Conn>>,
    /// Single-use inspector token -> context, from [`Host::open_inspector`].
    pi_tokens: HashMap<String, String>,
    roles: HashMap<u64, Role>,
    unknown: HashSet<String>,
}

struct Slot {
    uuid: String,
    conn: Option<Arc<Conn>>,
    global: Value,
    run: Option<Run>,
}

/// A supervised plugin process. The waiter thread owns the `Child` and blocks in `wait`, so the
/// rest of the host only keeps this handle; `stop` kills by pid.
struct Run {
    stop: Arc<AtomicBool>,
    /// Process id while alive, `None` between a crash and the next attempt (nothing to kill).
    pid: Option<u32>,
}

/// Restart delays: 1 s, 2 s, 4 s … capped at 60 s. A run that lasted this long resets the count.
const RESTART_MIN: Duration = Duration::from_secs(1);
const RESTART_MAX: Duration = Duration::from_secs(60);
const RESTART_RESET: Duration = Duration::from_secs(60);

/// Largest inbound frame or whole message, per socket. A 288x288 base64 PNG `setImage` stays under
/// 1 MiB, so 4 MiB leaves a wide margin while bounding what one local plugin or browser page can
/// make the daemon buffer (tungstenite defaults to 16 MiB per frame and 64 MiB per message).
pub const MAX_WS_MESSAGE: usize = 4 * 1024 * 1024;

fn restart_delay(attempt: u32) -> Duration {
    RESTART_MIN
        .saturating_mul(1 << attempt.min(6))
        .min(RESTART_MAX)
}

#[derive(Clone)]
enum Role {
    Plugin(String),
    /// Property inspector bound to this context.
    Pi(String),
}

/// Write half of a socket.
struct Conn {
    id: u64,
    /// Admitted only because of the opaque `null` origin (sandboxed PI iframe): may register a
    /// property inspector, never a plugin.
    opaque: bool,
    ws: Mutex<WebSocket<TcpStream>>,
    raw: TcpStream,
}

impl Conn {
    fn send(&self, msg: Message) {
        let mut ws = self.ws.lock().unwrap_or_else(|e| e.into_inner());
        if let Err(e) = ws.send(msg) {
            log::debug!("socket {}: send failed: {e}", self.id);
        }
    }

    fn close(&self) {
        let _ = self.raw.shutdown(Shutdown::Both);
    }
}

/// Side effects collected under the state lock and run after it is released.
#[derive(Default)]
struct Fx {
    sends: Vec<(Arc<Conn>, String)>,
    outputs: Vec<Output>,
    close: Option<Arc<Conn>>,
}

impl Fx {
    fn send(&mut self, conn: Option<&Arc<Conn>>, text: String) {
        if let Some(c) = conn {
            self.sends.push((c.clone(), text));
        }
    }
}

fn instance_msg(event: &str, i: &Instance) -> String {
    json!({
        "event": event, "action": i.action, "context": i.context, "device": i.device,
        "payload": {"settings": i.settings, "coordinates": {"column": i.column, "row": i.row},
                    "controller": i.controller, "state": i.state, "isInMultiAction": false},
    })
    .to_string()
}

fn global_msg(settings: &Value) -> String {
    json!({"event": "didReceiveGlobalSettings", "payload": {"settings": settings}}).to_string()
}

impl Host {
    /// Binds `127.0.0.1:<port>` and starts accepting sockets.
    pub fn start(cfg: Config, events: impl Events) -> io::Result<Host> {
        let listener = TcpListener::bind(("127.0.0.1", cfg.port))?;
        let port = listener.local_addr()?.port();
        let host = Host {
            inner: Arc::new(Inner {
                origins: Mutex::new(cfg.origins.clone()),
                cfg,
                port,
                events: Box::new(events),
                state: Mutex::default(),
                next_id: AtomicU64::new(1),
            }),
        };
        let h = host.clone();
        std::thread::Builder::new()
            .name("host-accept".into())
            .spawn(move || {
                for stream in listener.incoming() {
                    match stream {
                        Ok(s) => {
                            let h = h.clone();
                            std::thread::spawn(move || h.serve(s));
                        }
                        Err(e) => log::warn!("accept failed: {e}"),
                    }
                }
            })?;
        Ok(host)
    }

    /// The port actually bound.
    pub fn port(&self) -> u16 {
        self.inner.port
    }

    /// Allows a browser origin after the host started. The web editor binds a random port, so its
    /// origin cannot be in [`Config::origins`] at startup. Exact match, like the configured list.
    pub fn allow_origin(&self, origin: impl Into<String>) {
        let origin = origin.into();
        let mut origins = self.inner.origins.lock().unwrap_or_else(|e| e.into_inner());
        if !origins.contains(&origin) {
            origins.push(origin);
        }
    }

    fn lock(&self) -> MutexGuard<'_, State> {
        self.inner.state.lock().unwrap_or_else(|e| e.into_inner())
    }

    /// Registers a plugin without starting it and returns the UUID it must register with. A
    /// previous UUID for the same plugin stops being accepted. [`Host::launch`] calls this; use it
    /// directly for plugins started some other way.
    pub fn add(&self, plugin: &Plugin) -> String {
        let uuid = launch::random_uuid();
        let mut st = self.lock();
        st.uuids.retain(|_, id| id != &plugin.id);
        st.uuids.insert(uuid.clone(), plugin.id.clone());
        let slot = st.plugins.entry(plugin.id.clone()).or_insert_with(|| Slot {
            uuid: String::new(),
            conn: None,
            global: json!({}),
            run: None,
        });
        slot.uuid = uuid.clone();
        uuid
    }

    /// Starts a plugin process (`.exe` directly, `.js/.mjs/.cjs` through node) and supervises it: if
    /// it exits on its own it is relaunched with exponential backoff. A running instance of the
    /// same plugin is stopped first (and is not restarted). `.html` plugins return `Unsupported`.
    pub fn launch(&self, plugin: Plugin) -> io::Result<()> {
        self.stop(&plugin.id);
        let Some((child, stop)) = self.spawn(&plugin, None)? else {
            return Ok(());
        };
        self.watch(plugin, child, stop)
    }

    /// Starts one process and installs its run handle. With `expect`, gives up (`Ok(None)`) unless
    /// the current run is still that one, so a late restart cannot revive a stopped plugin.
    fn spawn(
        &self,
        plugin: &Plugin,
        expect: Option<&Arc<AtomicBool>>,
    ) -> io::Result<Option<(Child, Arc<AtomicBool>)>> {
        if expect.is_some_and(|current| !self.is_current(&plugin.id, current)) {
            return Ok(None);
        }
        let uuid = self.add(plugin);
        let info = launch::info(plugin, &self.inner.cfg.devices, &self.inner.cfg.language);
        let mut cmd = launch::command(plugin, &self.inner.cfg.node, self.inner.port, &uuid, &info)
            .ok_or_else(|| {
                io::Error::new(
                    io::ErrorKind::Unsupported,
                    format!("cannot run {}", plugin.code_path),
                )
            })?;
        let mut child = cmd.spawn()?;
        let stop = Arc::new(AtomicBool::new(false));
        let installed = {
            let mut st = self.lock();
            match st.plugins.get_mut(&plugin.id) {
                Some(slot)
                    if expect.is_none_or(|c| {
                        slot.run.as_ref().is_some_and(|r| Arc::ptr_eq(&r.stop, c))
                    }) =>
                {
                    slot.run = Some(Run {
                        stop: stop.clone(),
                        pid: Some(child.id()),
                    });
                    true
                }
                _ => false,
            }
        };
        if !installed {
            let _ = child.kill();
            let _ = child.wait();
            return Ok(None);
        }
        log::info!("{}: started pid {}", plugin.id, child.id());
        Ok(Some((child, stop)))
    }

    fn is_current(&self, plugin: &str, flag: &Arc<AtomicBool>) -> bool {
        self.lock()
            .plugins
            .get(plugin)
            .and_then(|s| s.run.as_ref())
            .is_some_and(|r| Arc::ptr_eq(&r.stop, flag))
    }

    /// Starts the one waiter thread of a plugin. It blocks on `Child::wait`; nothing polls.
    fn watch(&self, plugin: Plugin, child: Child, stop: Arc<AtomicBool>) -> io::Result<()> {
        let host = self.clone();
        let id = plugin.id.clone();
        let name = format!("{}-wait", plugin.id);
        std::thread::Builder::new()
            .name(name)
            .spawn(move || host.supervise(plugin, child, stop))
            .map(|_| ())
            .map_err(|e| {
                self.stop(&id);
                e
            })
    }

    /// Blocks until the child exits. A crash is retried with backoff; a `stop` (flag set, or run
    /// replaced) ends the thread without restarting.
    fn supervise(self, plugin: Plugin, mut child: Child, mut stop: Arc<AtomicBool>) {
        let mut attempt = 0u32;
        loop {
            let started = Instant::now();
            let status = child.wait();
            let uptime = started.elapsed();
            {
                let mut st = self.lock();
                let current = st
                    .plugins
                    .get_mut(&plugin.id)
                    .and_then(|s| s.run.as_mut())
                    .filter(|r| Arc::ptr_eq(&r.stop, &stop));
                match current {
                    Some(run) => run.pid = None,
                    None => return, // stopped or relaunched while we waited
                }
            }
            if stop.load(Ordering::SeqCst) {
                return;
            }
            if uptime >= RESTART_RESET {
                attempt = 0;
            }
            let delay = restart_delay(attempt);
            attempt = attempt.saturating_add(1);
            log::warn!(
                "{}: {status:?} after {} ms, restarting in {} ms",
                plugin.id,
                uptime.as_millis(),
                delay.as_millis()
            );
            std::thread::sleep(delay);
            if stop.load(Ordering::SeqCst) {
                self.clear(&plugin.id, &stop);
                return;
            }
            match self.spawn(&plugin, Some(&stop)) {
                Ok(Some((child_, stop_))) => {
                    child = child_;
                    stop = stop_;
                }
                Ok(None) => return,
                Err(e) => {
                    log::error!("{}: restart failed: {e}", plugin.id);
                    self.clear(&plugin.id, &stop);
                    return;
                }
            }
        }
    }

    fn clear(&self, plugin: &str, flag: &Arc<AtomicBool>) {
        if let Some(slot) = self.lock().plugins.get_mut(plugin) {
            if slot
                .run
                .as_ref()
                .is_some_and(|r| Arc::ptr_eq(&r.stop, flag))
            {
                slot.run = None;
            }
        }
    }

    /// Kills a launched plugin and closes its socket. Placed instances are kept and re-sent
    /// (`willAppear`) when the plugin registers again. The waiter thread reaps the process.
    pub fn stop(&self, plugin_id: &str) {
        let (run, conn) = {
            let mut st = self.lock();
            let Some(slot) = st.plugins.get_mut(plugin_id) else {
                return;
            };
            (slot.run.take(), slot.conn.take())
        };
        if let Some(c) = conn {
            c.close();
        }
        if let Some(run) = run {
            run.stop.store(true, Ordering::SeqCst);
            if let Some(pid) = run.pid {
                terminate(pid);
            }
        }
    }

    /// Seeds a plugin's global settings from the daemon's store (no event is sent). Creates the
    /// slot when needed, so it may be called before [`Host::launch`].
    pub fn load_global_settings(&self, plugin_id: &str, settings: Value) {
        let mut st = self.lock();
        let slot = st
            .plugins
            .entry(plugin_id.to_string())
            .or_insert_with(|| Slot {
                uuid: String::new(),
                conn: None,
                global: json!({}),
                run: None,
            });
        slot.global = settings;
    }

    /// Places an action on a key and returns its new random context. `willAppear` is sent now if
    /// the plugin is connected, otherwise when it registers.
    pub fn appear(&self, mut inst: Instance) -> String {
        inst.context = launch::random_uuid();
        let context = inst.context.clone();
        let mut fx = Fx::default();
        {
            let mut st = self.lock();
            let conn = st.plugins.get(&inst.plugin).and_then(|s| s.conn.clone());
            fx.send(conn.as_ref(), instance_msg("willAppear", &inst));
            st.instances.insert(context.clone(), inst);
        }
        self.run(fx);
        context
    }

    /// Issues a single-use property-inspector UUID for a context. The web editor passes it to the
    /// PI as `inPropertyInspectorUUID`; `registerPropertyInspector` with anything else is refused.
    pub fn open_inspector(&self, context: &str) -> Option<String> {
        let mut st = self.lock();
        if !st.instances.contains_key(context) {
            return None;
        }
        let token = launch::random_uuid();
        st.pi_tokens.insert(token.clone(), context.to_string());
        Some(token)
    }

    /// Removes an action from its key and sends `willDisappear`.
    pub fn disappear(&self, context: &str) {
        let mut fx = Fx::default();
        {
            let mut st = self.lock();
            let Some(inst) = st.instances.remove(context) else {
                return;
            };
            let conn = st.plugins.get(&inst.plugin).and_then(|s| s.conn.clone());
            fx.send(conn.as_ref(), instance_msg("willDisappear", &inst));
            st.pi_tokens.retain(|_, c| c != context);
            if let Some(pi) = st.pis.remove(context) {
                fx.close = Some(pi);
            }
        }
        self.run(fx);
    }

    /// Injects a key press (`keyDown`) or release (`keyUp`). Returns false if the context is
    /// unknown or its plugin is not connected.
    pub fn key(&self, context: &str, down: bool) -> bool {
        let mut fx = Fx::default();
        {
            let st = self.lock();
            let Some(inst) = st.instances.get(context) else {
                return false;
            };
            let Some(conn) = st.plugins.get(&inst.plugin).and_then(|s| s.conn.clone()) else {
                return false;
            };
            fx.send(
                Some(&conn),
                instance_msg(if down { "keyDown" } else { "keyUp" }, inst),
            );
        }
        self.run(fx);
        true
    }

    fn run(&self, fx: Fx) {
        for (conn, text) in fx.sends {
            conn.send(Message::text(text));
        }
        for out in fx.outputs {
            self.inner.events.output(out);
        }
        if let Some(c) = fx.close {
            c.close();
        }
    }

    fn serve(&self, stream: TcpStream) {
        let id = self.inner.next_id.fetch_add(1, Ordering::Relaxed);
        let (mut reader, conn) = match self.handshake(stream, id) {
            Ok(x) => x,
            Err(e) => return log::debug!("socket {id}: handshake failed: {e}"),
        };
        loop {
            match reader.read() {
                Ok(Message::Text(t)) => match serde_json::from_str::<Value>(&t) {
                    Ok(msg) => self.handle(&conn, msg),
                    Err(e) => log::debug!("socket {id}: bad JSON: {e}"),
                },
                Ok(Message::Ping(p)) => conn.send(Message::Pong(p)),
                Ok(Message::Close(_)) => {
                    conn.send(Message::Close(None));
                    break;
                }
                Ok(_) => {}
                Err(_) => break,
            }
        }
        conn.close();
        self.disconnected(&conn);
    }

    fn handshake(
        &self,
        stream: TcpStream,
        id: u64,
    ) -> Result<(WebSocket<Muted>, Arc<Conn>), Box<dyn std::error::Error>> {
        stream.set_nodelay(true)?;
        let writer = WebSocket::from_raw_socket(stream.try_clone()?, WsRole::Server, None);
        let raw = stream.try_clone()?;
        // A sandboxed PI iframe has an opaque origin (`null`). Admit that literal only while an
        // inspector session exists; registering still requires the single-use token, so a page
        // that learns nothing from the editor cannot reach a plugin.
        let inspector_open = {
            let st = self.lock();
            !st.pi_tokens.is_empty() || !st.pis.is_empty()
        };
        let mut allowed = self
            .inner
            .origins
            .lock()
            .unwrap_or_else(|e| e.into_inner())
            .clone();
        if inspector_open {
            allowed.push("null".into());
        }
        let mut opaque = false;
        let config = WebSocketConfig::default()
            .max_frame_size(Some(MAX_WS_MESSAGE))
            .max_message_size(Some(MAX_WS_MESSAGE));
        let mut reader = tungstenite::accept_hdr_with_config(
            Muted {
                s: stream,
                mute: false,
            },
            |req: &Request, resp| {
                opaque = req.headers().get("origin").and_then(|v| v.to_str().ok()) == Some("null");
                check_origin(&allowed, req, resp)
            },
            Some(config),
        )
        .map_err(|e| e.to_string())?;
        // From here the reader only reads; its automatic pong/close replies are discarded and
        // sent through the writer instead, so two threads never write frames to the socket.
        reader.get_mut().mute = true;
        Ok((
            reader,
            Arc::new(Conn {
                id,
                opaque,
                ws: Mutex::new(writer),
                raw,
            }),
        ))
    }

    fn disconnected(&self, conn: &Arc<Conn>) {
        let mut fx = Fx::default();
        {
            let mut st = self.lock();
            match st.roles.remove(&conn.id) {
                Some(Role::Plugin(id)) => {
                    if let Some(slot) = st.plugins.get_mut(&id) {
                        if slot.conn.as_ref().is_some_and(|c| c.id == conn.id) {
                            slot.conn = None;
                            log::info!("{id}: disconnected");
                        }
                    }
                }
                Some(Role::Pi(ctx)) => {
                    if st.pis.get(&ctx).is_some_and(|c| c.id == conn.id) {
                        st.pis.remove(&ctx);
                        if let Some(inst) = st.instances.get(&ctx) {
                            let plugin = st.plugins.get(&inst.plugin).and_then(|s| s.conn.clone());
                            fx.send(
                                plugin.as_ref(),
                                pi_event("propertyInspectorDidDisappear", inst),
                            );
                        }
                    }
                }
                None => {}
            }
        }
        self.run(fx);
    }

    fn handle(&self, conn: &Arc<Conn>, msg: Value) {
        let event = msg["event"].as_str().unwrap_or_default();
        let mut fx = Fx::default();
        {
            let mut st = self.lock();
            match st.roles.get(&conn.id).cloned() {
                None => self.register(&mut st, conn, event, &msg, &mut fx),
                Some(role) => command(&mut st, conn, role, event, &msg, &mut fx),
            }
        }
        self.run(fx);
    }

    fn register(&self, st: &mut State, conn: &Arc<Conn>, event: &str, msg: &Value, fx: &mut Fx) {
        let uuid = msg["uuid"].as_str().unwrap_or_default();
        match event {
            "registerPlugin" if !conn.opaque && st.uuids.contains_key(uuid) => {
                let id = st.uuids[uuid].clone();
                log::info!("{id}: registered");
                st.roles.insert(conn.id, Role::Plugin(id.clone()));
                if let Some(old) = st
                    .plugins
                    .get_mut(&id)
                    .and_then(|s| s.conn.replace(conn.clone()))
                {
                    fx.close = Some(old);
                }
                for d in &self.inner.cfg.devices {
                    let mut m = json!({"event": "deviceDidConnect", "device": d.id});
                    m["deviceInfo"] = d.info();
                    fx.send(Some(conn), m.to_string());
                }
                let mut mine: Vec<&Instance> =
                    st.instances.values().filter(|i| i.plugin == id).collect();
                mine.sort_by_key(|i| (i.device.clone(), i.row, i.column));
                for i in mine {
                    fx.send(Some(conn), instance_msg("willAppear", i));
                }
            }
            "registerPropertyInspector" if st.pi_tokens.contains_key(uuid) => {
                let ctx = st.pi_tokens.remove(uuid).unwrap_or_default();
                st.roles.insert(conn.id, Role::Pi(ctx.clone()));
                if let Some(old) = st.pis.insert(ctx.clone(), conn.clone()) {
                    fx.close = Some(old);
                }
                let inst = &st.instances[&ctx];
                let plugin = st.plugins.get(&inst.plugin).and_then(|s| s.conn.clone());
                fx.send(
                    plugin.as_ref(),
                    pi_event("propertyInspectorDidAppear", inst),
                );
                fx.send(Some(conn), instance_msg("didReceiveSettings", inst));
            }
            _ => {
                log::warn!("socket {}: rejected {event:?} with uuid {uuid:?}", conn.id);
                fx.close = Some(conn.clone());
            }
        }
    }
}

fn pi_event(event: &str, i: &Instance) -> String {
    json!({"event": event, "action": i.action, "context": i.context, "device": i.device})
        .to_string()
}

/// One command from a registered socket.
fn command(st: &mut State, conn: &Arc<Conn>, role: Role, event: &str, msg: &Value, fx: &mut Fx) {
    let payload = &msg["payload"];
    let (plugin_id, pi_ctx) = match role {
        Role::Plugin(id) => (id, None),
        Role::Pi(ctx) => match st.instances.get(&ctx) {
            Some(i) => (i.plugin.clone(), Some(ctx)),
            None => return,
        },
    };
    let plugin_conn = st.plugins.get(&plugin_id).and_then(|s| s.conn.clone());

    // Plugin-wide commands.
    match event {
        "openUrl" => {
            if let Some(url) = payload["url"].as_str() {
                fx.outputs.push(Output::OpenUrl(url.to_string()));
            }
            return;
        }
        "logMessage" => {
            return log::info!(
                "[{plugin_id}] {}",
                payload["message"].as_str().unwrap_or_default()
            )
        }
        "setGlobalSettings" => {
            if let Some(slot) = st.plugins.get_mut(&plugin_id) {
                slot.global = payload.clone();
            }
            fx.outputs.push(Output::GlobalSettings {
                plugin: plugin_id.clone(),
                settings: payload.clone(),
            });
            // Like Elgato, echo to the other side only.
            if pi_ctx.is_some() {
                fx.send(plugin_conn.as_ref(), global_msg(payload));
            } else {
                for (ctx, pi) in &st.pis {
                    if st.instances.get(ctx).is_some_and(|i| i.plugin == plugin_id) {
                        fx.send(Some(pi), global_msg(payload));
                    }
                }
            }
            return;
        }
        "getGlobalSettings" => {
            let global = st
                .plugins
                .get(&plugin_id)
                .map(|s| s.global.clone())
                .unwrap_or_else(|| json!({}));
            return fx.send(Some(conn), global_msg(&global));
        }
        _ => {}
    }

    // Per-instance commands. A PI acts on its own context whatever it puts in `context`; a plugin
    // may only touch its own instances.
    let ctx = pi_ctx
        .clone()
        .unwrap_or_else(|| msg["context"].as_str().unwrap_or_default().to_string());
    let Some(inst) = st.instances.get_mut(&ctx).filter(|i| i.plugin == plugin_id) else {
        return log::debug!("[{plugin_id}] {event} for unknown context {ctx:?}");
    };
    let state = payload["state"].as_u64().map(|s| s as u32);
    match event {
        // target 2 is software-only; there is no software display yet.
        "setImage" | "setTitle" if payload["target"].as_u64() == Some(2) => {}
        "setImage" => fx.outputs.push(Output::Image {
            key: inst.key(),
            image: payload["image"].as_str().unwrap_or_default().to_string(),
            state,
        }),
        "setTitle" => fx.outputs.push(Output::Title {
            key: inst.key(),
            title: payload["title"].as_str().unwrap_or_default().to_string(),
            state,
        }),
        "setState" => {
            inst.state = state.unwrap_or(0);
            fx.outputs.push(Output::State {
                key: inst.key(),
                state: inst.state,
            });
        }
        "showOk" => fx.outputs.push(Output::ShowOk(inst.key())),
        "showAlert" => fx.outputs.push(Output::ShowAlert(inst.key())),
        "setSettings" => {
            inst.settings = payload.clone();
            fx.outputs.push(Output::Settings {
                context: ctx.clone(),
                settings: payload.clone(),
            });
            let text = instance_msg("didReceiveSettings", inst);
            if pi_ctx.is_some() {
                fx.send(plugin_conn.as_ref(), text);
            } else {
                fx.send(st.pis.get(&ctx), text);
            }
        }
        "getSettings" => fx.send(Some(conn), instance_msg("didReceiveSettings", inst)),
        "sendToPropertyInspector" if pi_ctx.is_none() => {
            let text = json!({"event": "sendToPropertyInspector", "action": inst.action, "context": ctx, "payload": payload});
            fx.send(st.pis.get(&ctx), text.to_string());
        }
        "sendToPlugin" if pi_ctx.is_some() => {
            let text = json!({"event": "sendToPlugin", "action": inst.action, "context": ctx, "payload": payload});
            fx.send(plugin_conn.as_ref(), text.to_string());
        }
        _ => {
            if st.unknown.insert(event.to_string()) {
                log::warn!("[{plugin_id}] dropping unsupported command {event:?} (logged once)");
            }
        }
    }
}

/// Browsers send an Origin header; native plugin processes do not. A browser socket is accepted
/// only from an origin listed in [`Config::origins`] (exact match) or, while an inspector session
/// exists, from the opaque `null` origin of a sandboxed PI iframe. Registering as a PI still
/// requires its single-use token, so an unrelated page cannot reach plugins.
fn check_origin(
    allowed: &[String],
    req: &Request,
    resp: Response,
) -> Result<Response, ErrorResponse> {
    let mut origins = req.headers().get_all("origin").iter();
    let Some(origin) = origins.next() else {
        return Ok(resp);
    };
    let origin = origin.to_str().unwrap_or_default();
    if origins.next().is_none() && allowed.iter().any(|a| a == origin) {
        return Ok(resp);
    }
    log::warn!("rejected socket from origin {origin:?}");
    let mut err = ErrorResponse::new(Some("forbidden origin".into()));
    *err.status_mut() = tungstenite::http::StatusCode::FORBIDDEN;
    Err(err)
}

/// Kills a process by pid. The waiter thread owns the `Child` (it is blocked in `wait`), so this is
/// the only handle left; `taskkill` is part of Windows and the daemon is Windows-only, so no crate.
#[cfg(windows)]
fn terminate(pid: u32) {
    use std::os::windows::process::CommandExt;
    const CREATE_NO_WINDOW: u32 = 0x0800_0000;
    let _ = Command::new("taskkill")
        .args(["/PID", &pid.to_string(), "/F"])
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .creation_flags(CREATE_NO_WINDOW)
        .status();
}

#[cfg(not(windows))]
fn terminate(pid: u32) {
    let _ = Command::new("kill").arg(pid.to_string()).status();
}

/// Read side of a socket. Writes are dropped once `mute` is set (after the handshake).
struct Muted {
    s: TcpStream,
    mute: bool,
}

impl Read for Muted {
    fn read(&mut self, buf: &mut [u8]) -> io::Result<usize> {
        self.s.read(buf)
    }
}

impl Write for Muted {
    fn write(&mut self, buf: &[u8]) -> io::Result<usize> {
        if self.mute {
            Ok(buf.len())
        } else {
            self.s.write(buf)
        }
    }

    fn flush(&mut self) -> io::Result<()> {
        self.s.flush()
    }
}

